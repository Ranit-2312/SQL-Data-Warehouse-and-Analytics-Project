/*
===============================================================================
Magnitude Analysis
===============================================================================
Purpose:
    - To quantify data and group results by specific dimensions.
    - For understanding data distribution across categories.

SQL Functions Used:
    - Aggregate Functions: SUM(), COUNT(), AVG()
    - GROUP BY, ORDER BY
===============================================================================
*/

-- FIND TOTAL CUSTOMERS BY COUNTRIES
SELECT 
  DISTINCT country,COUNT(customer_key) AS customer_per_country
FROM gold.dim_customers
GROUP BY 
  country 
ORDER BY
  customer_per_country DESC;

-- FIND TOTAL CUSTOMERS BY GENDER
SELECT 
  DISTINCT gender,COUNT(customer_key) AS customer_per_gender
FROM gold.dim_customers
GROUP BY 
  gender 
ORDER BY
  customer_per_gender DESC;

-- FIND TOTAL PRODUCTS BY CATEGORY
SELECT 
  DISTINCT category, COUNT(product_key) AS products_per_category
FROM gold.dim_products
GROUP BY 
  category 
ORDER BY 
  categproducts_per_category DESC;

-- WHAT IS THE AVERAGE COSTS IN EACH CATEGORY?
SELECT 
  DISTINCT category, ROUND(AVG(product_cost)) AS avg_price_per_category
FROM gold.dim_products
GROUP BY 
  category 
ORDER BY
  avg_price_per_category DESC;

-- WHAT IS THE TOTAL REVENUE GENERATED FOR EACH CATEGORY?
SELECT 
  DISTINCT p.category, ROUND(SUM(f.sales_amount)) AS revenue_per_category
FROM 
  gold.dim_products p LEFT JOIN gold.fact_sales f
  ON p.product_key = f.product_key
GROUP BY 
  category
ORDER BY
  revenue_per_category DESC;

-- FIND TOTAL REVENUE IS GENERATED BY EACH CUSTOMER
SELECT 
	c.customer_key, 
	c.first_name, 
	c.last_name, 
	SUM(f.sales_amount) AS revenue_per_customer
FROM 
  gold.dim_customers c LEFT JOIN gold.fact_sales f
	ON c.customer_key = f.customer_key
GROUP BY 
  c.customer_key, c.first_name, c.last_name
ORDER BY
  revenue_per_customer DESC;

-- WHAT IS THE DISTRIBUTION OF SOLD ITEMS ACROSS COUNTRIES?
SELECT 
	c.country,
	SUM(f.quantity) AS total_quantity
FROM 
  gold.dim_customers c LEFT JOIN gold.fact_sales f
	ON f.customer_key = c.customer_key
GROUP BY
  c.country
ORDER BY
  total_quantity DESC;
